"""Evaluation harness (plan8 Phase 5): score the DecisionGraph against a chunk-RAG
baseline over the same source corpus, on two metrics.

- Timeline Faithfulness — over a set of as-of checkpoints, does the system report
  the option that was authoritative at that time? Ground truth is the fixture's
  human-authored decision timeline (below), so BOTH systems (and the reducer's
  as_of) are measured against an independent reference, not against each other.

- Context Contamination Rate — of the context a system assembles for an agent,
  what fraction asserts a currently-inactive option as the current decision? A
  chunk retriever presents every retrieved passage flatly; a Context Pack fences
  inactive options with `must_not_use_as_current`.

Deterministic — no embeddings, network, or randomness.

Usage: python evaluation/harness.py [--ir <dir>] [--target <id>]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ppir.config import REPO_ROOT                                    # noqa: E402
from ppir.atoms import load_atoms                                    # noqa: E402
from compilers.compile_decision_projection import project_target     # noqa: E402
from compilers.compile_context_pack import build as build_pack       # noqa: E402
from evaluation import chunk_baseline as cb                          # noqa: E402

# Human-authored authoritative timeline for the a→a2 fixture (independent ground
# truth): what SHOULD the current decision be, as of each date?
TIMELINE = [
    ("2026-07-03", "a"),     # adopted 07-01
    ("2026-07-08", None),    # deferred 07-05 — no active option
    ("2026-07-11", None),    # reopened 07-10 — undecided
    ("2026-07-13", "a2"),    # replaced a→a2 on 07-12
    ("2026-07-16", "a2"),    # now: 07-15 signal is not a decision
]


def _slug(option_id):
    return option_id.split(".")[-1] if option_id else None


def _graph_answer(atoms, target_id, as_of):
    opts = project_target(atoms, target_id, as_of=as_of)["current_option"]
    return _slug(opts[0]) if opts else None


def _baseline_answer(atoms, target_id, as_of, chunks):
    return _slug(cb.answer(chunks, as_of=as_of))


def _timeline_faithfulness(answer_fn):
    hits = [(d, exp, answer_fn(d)) for d, exp in TIMELINE]
    score = sum(1 for _, exp, got in hits if got == exp) / len(TIMELINE)
    return round(score, 3), hits


def _contamination_rate(items, current_slugs):
    """items: [{slug, asserted_as_current}]. Contaminated = asserted as current
    but not actually current."""
    asserting = [i for i in items if i["slug"] and i["asserted_as_current"]]
    if not asserting:
        return 0.0, 0, 0
    bad = [i for i in asserting if i["slug"] not in current_slugs]
    return round(len(bad) / len(asserting), 3), len(bad), len(asserting)


def evaluate(atoms: dict, target_id: str) -> dict:
    chunks = cb.chunk_sources(atoms, target_id)
    now = TIMELINE[-1][0]
    current_slugs = {exp for _, exp in [TIMELINE[-1]] if exp}

    graph_tf, graph_hits = _timeline_faithfulness(
        lambda d: _graph_answer(atoms, target_id, d))
    base_tf, base_hits = _timeline_faithfulness(
        lambda d: _baseline_answer(atoms, target_id, d, chunks))

    # Baseline context: every retrieved passage, presented as current.
    base_items = [{"slug": _slug(c["option"]), "asserted_as_current": True}
                  for c in cb.retrieve(chunks, as_of=now)]
    base_ccr, base_bad, base_tot = _contamination_rate(base_items, current_slugs)

    # Graph context: the Context Pack — current asserted, inactive fenced.
    pack = build_pack(atoms, target_id)
    pack_items = [{"slug": _slug(c["option"]), "asserted_as_current": True}
                  for c in pack["authority"]["current"]]
    pack_items += [{"slug": _slug(i["option"]), "asserted_as_current": False}
                   for i in pack["authority"]["inactive"]]
    graph_ccr, graph_bad, graph_tot = _contamination_rate(pack_items, current_slugs)

    return {
        "target": target_id,
        "now": now,
        "ground_truth_now": sorted(current_slugs),
        "timeline": TIMELINE,
        "baseline": {
            "answer_now": _baseline_answer(atoms, target_id, now, chunks),
            "timeline_faithfulness": base_tf,
            "timeline_hits": base_hits,
            "contamination_rate": base_ccr,
            "contaminated": base_bad, "context_size": base_tot,
        },
        "graph": {
            "answer_now": _graph_answer(atoms, target_id, now),
            "timeline_faithfulness": graph_tf,
            "timeline_hits": graph_hits,
            "contamination_rate": graph_ccr,
            "contaminated": graph_bad, "context_size": graph_tot,
        },
    }


BANNER = "<!-- DO NOT EDIT — generated by evaluation/harness.py. -->"


def render_report(m: dict) -> str:
    b, g = m["baseline"], m["graph"]
    L = [BANNER, "# Decision Evolution — Evaluation Report", "",
         f"**Target:** `{m['target']}`  |  **As of:** {m['now']}  "
         f"|  **Authoritative now:** {', '.join(m['ground_truth_now'])}", "",
         "동일 소스 코퍼스에 대해 chunk-RAG baseline과 DecisionGraph를 대조한다.", "",
         "## Metrics", "",
         "| System | 현재 답 | Timeline Faithfulness | Context Contamination |",
         "|---|---|---|---|",
         f"| chunk-RAG baseline | **{b['answer_now']}** | {b['timeline_faithfulness']:.2f} "
         f"| {b['contamination_rate']:.2f} ({b['contaminated']}/{b['context_size']}) |",
         f"| DecisionGraph | **{g['answer_now']}** | {g['timeline_faithfulness']:.2f} "
         f"| {g['contamination_rate']:.2f} ({g['contaminated']}/{g['context_size']}) |",
         "",
         "## Timeline detail (as-of → expected / baseline / graph)", "",
         "| As of | Authoritative | chunk-RAG | DecisionGraph |",
         "|---|---|---|---|"]
    for (d, exp, gb), (_, _, gg) in zip(b["timeline_hits"], g["timeline_hits"]):
        def _m(got, want):
            return f"{got or '—'} {'✓' if got == want else '✗'}"
        L.append(f"| {d} | {exp or '—'} | {_m(gb, exp)} | {_m(gg, exp)} |")
    L += ["",
          "## 해석", "",
          "- **Timeline Faithfulness**: baseline은 최신 소스 문장을 좇아, 보류·재개 구간과 "
          "07-15 신호(‘a 재차 필요’)에서 오답한다. DecisionGraph는 governance-rule reduce로 "
          "각 시점의 권위 결정을 재현한다.",
          "- **Context Contamination**: baseline이 조립한 컨텍스트는 비활성 옵션 a를 현재처럼 "
          "제시한다. Context Pack은 a를 `must_not_use_as_current`로 펜싱해 오염 0.", ""]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ir", default="tests/fixtures/decision-evolution-a-to-a2")
    ap.add_argument("--target", default="SHOP.TARGET.business_need_x_resolution")
    ap.add_argument("--out", default="compiled/reports/decision-eval-report.md")
    args = ap.parse_args()
    atoms = load_atoms(REPO_ROOT / args.ir)
    metrics = evaluate(atoms, args.target)
    out = REPO_ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_report(metrics), encoding="utf-8")
    b, g = metrics["baseline"], metrics["graph"]
    print(f"eval → {out.relative_to(REPO_ROOT)}")
    print(f"  baseline: answer={b['answer_now']} TF={b['timeline_faithfulness']} "
          f"CCR={b['contamination_rate']}")
    print(f"  graph:    answer={g['answer_now']} TF={g['timeline_faithfulness']} "
          f"CCR={g['contamination_rate']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
