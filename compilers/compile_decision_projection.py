"""Compile a CurrentDecisionProjection per DecisionTarget (plan8 — Level: governance).

The core of the Decision Evolution Graph. A DecisionTarget accumulates a stream of
DecisionEvents (adopt / defer / reopen / replace / confirm ...). The current
authoritative decision is NOT max(decision_time) of the sources — it is
`reduce(events, governance_rules)`:

    1. only accepted governance events count           (a raw signal never moves the state)
    2. same target
    3. (future) effective_from valid at 'now'
    4. supersedes/replaces relations resolve conflicts
    5. (future) higher authority_level wins
    6. decision_time orders the fold
    7. recorded_at is aux only

This file is a COMPILE PRODUCT generator — never hand-author a projection.

Usage: python compilers/compile_decision_projection.py [--ir tests/fixtures/decision-evolution-a-to-a2]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ppir.config import REPO_ROOT               # noqa: E402
from ppir.atoms import load_atoms                # noqa: E402
from compilers import provenance                 # noqa: E402

BANNER = "# DO NOT EDIT — generated by compile_decision_projection from DecisionEvents."

# authority ranking (rule 5): a lower authority cannot override a higher one.
_AUTH = {"proposal": 0, "team": 1, "product": 2, "executive": 3}
_DEFAULT_AUTH = 2  # an event with no explicit level is treated as product-level


def _short(option_id: str) -> str:
    return option_id.split(".")[-1]


def _auth(event: dict) -> int:
    return _AUTH.get(event.get("authority_level"), _DEFAULT_AUTH)


def _events_for_target(atoms: dict, target_id: str, as_of: str | None = None) -> list:
    events = [e["data"] for e in atoms.values()
              if e["data"].get("kind") == "DecisionEvent"
              and e["data"].get("target_ref") == target_id]
    # rule 1: only accepted governance events move the state.
    events = [e for e in events if e.get("commitment_level") == "accepted"]
    # rule 3: an event effective in the future is not yet in force at `as_of`.
    # It takes effect at effective_from, or — absent that — when it was decided
    # (decision_time), never before. So a future-decided event with no explicit
    # effective_from must not leak into an earlier checkpoint.
    if as_of:
        def _in_force(e: dict) -> bool:
            t = e.get("effective_from") or (e.get("decision_time") or "")[:10]
            return not t or t <= as_of
        events = [e for e in events if _in_force(e)]
    # rule 6: decision_time orders the fold (ISO-8601 strings sort chronologically).
    events.sort(key=lambda e: e.get("decision_time", ""))
    return events


def _apply(event: dict, active: set, inactive: dict, state: str) -> str:
    """Fold one event into (active, inactive); return the resulting target state.
    Every event_type in the schema enum is handled — none raise."""
    et = event.get("event_type")
    selects = event.get("selects") or []
    replaces = event.get("replaces") or []
    affects = event.get("affects") or []
    accepted_or = lambda default: "accepted" if active else default  # noqa: E731

    if et == "propose_option":
        return accepted_or("open")                       # a candidate on the table, not adopted

    if et == "adopt_option":
        for oid in selects:
            active.add(oid); inactive.pop(oid, None)
        return "accepted"

    if et == "defer_option":
        for oid in (affects or selects):
            active.discard(oid); inactive[oid] = "deferred"
        return accepted_or("deferred")

    if et == "reject_option":
        for oid in (affects or selects):
            active.discard(oid); inactive[oid] = "rejected"
        return accepted_or("open")

    if et == "reopen_target":
        return "open"                                    # options keep state; target reopens

    if et in ("replace_option", "supersede_decision"):
        reason = (f"replaced_by_{_short(selects[0])}"
                  if et == "replace_option" and selects else "superseded")
        for oid in replaces:
            active.discard(oid); inactive[oid] = reason
        for oid in selects:
            active.add(oid); inactive.pop(oid, None)
        return accepted_or("open")

    if et == "narrow_scope":
        for oid in affects:
            active.discard(oid); inactive[oid] = "out_of_scope"
        return accepted_or(state)

    if et == "expand_scope":
        for oid in selects:                              # scope widened to re-include
            active.add(oid); inactive.pop(oid, None)
        return accepted_or(state)

    if et in ("refine_option", "amend_decision", "merge_target"):
        return accepted_or(state)                        # definition changes, not membership

    if et == "confirm_current":
        return accepted_or("open")

    if et == "cancel_target":
        for oid in list(active):
            inactive[oid] = "target_cancelled"
        active.clear()
        return "cancelled"

    if et == "split_target":
        return "superseded"                              # resolution moved to child targets

    return accepted_or(state)                            # declared-but-unknown: safe no-op


def project_target(atoms: dict, target_id: str, as_of: str | None = None) -> dict:
    target = atoms.get(target_id)
    tdata = target["data"] if target else {}
    events = _events_for_target(atoms, target_id, as_of)

    active: set = set()
    inactive: dict = {}
    state = "open"
    chain: list = []
    source_refs: list = []
    auth_level = -1                      # authority that established the current active option(s)
    for ev in events:
        # rule 5: a lower authority cannot disturb an option a higher authority set.
        disturbs = (set(ev.get("replaces") or []) | set(ev.get("affects") or [])) & active
        if disturbs and _auth(ev) < auth_level:
            continue
        before = set(active)
        state = _apply(ev, active, inactive, state)
        if active - before:              # this event established/added an active option
            auth_level = _auth(ev)
        reasons = ev.get("reason") or []
        chain.append(reasons[0] if reasons else ev.get("event_type"))
        for s in ev.get("source_refs") or []:
            if s not in source_refs:
                source_refs.append(s)

    # rule: a single-resolution target must not end with >1 active option.
    if tdata.get("current_resolution_policy") == "single" and len(active) > 1:
        state = "conflict"

    current_option = sorted(active)
    summaries = [atoms[o]["data"].get("summary", o) for o in current_option if o in atoms]

    return {
        "kind": "CurrentDecisionProjection",
        "id": target_id.replace(".TARGET.", ".PROJECTION.") + ".current",
        "track": "governance",
        "status": "accepted",
        "commitment_level": "accepted",
        "scope": tdata.get("scope", {}),
        "target_ref": target_id,
        "current_state": state,
        "current_option": current_option,
        "inactive_options": [{"option": k, "reason": inactive[k]} for k in sorted(inactive)],
        "current_summary": " ".join(summaries) if summaries else tdata.get("statement", ""),
        "decision_chain": chain,
        "generated_from_events": [e.get("id") for e in events],
        "source_refs": source_refs,
    }


def compile_all(atoms: dict) -> dict:
    targets = [e["data"]["id"] for e in atoms.values()
               if e["data"].get("kind") == "DecisionTarget"]
    return {tid: project_target(atoms, tid) for tid in sorted(targets)}


def run(ir_dir: Path, out_dir: Path) -> list:
    atoms = load_atoms(ir_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for tid, proj in compile_all(atoms).items():
        path = out_dir / f"{proj['id']}.yaml"
        body = BANNER + "\n" + yaml.safe_dump(proj, allow_unicode=True, sort_keys=False)
        path.write_text(provenance.stamp(body, "decision_projection", atoms, style="yaml"),
                        encoding="utf-8")
        written.append(path)
    return written


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ir", default="ir", help="atom dir to project over")
    ap.add_argument("--out", default="compiled/reports/decision-projections")
    args = ap.parse_args()
    written = run(REPO_ROOT / args.ir, REPO_ROOT / args.out)
    for p in written:
        print(f"  wrote {p.relative_to(REPO_ROOT)}")
    print(f"compile_decision_projection — {len(written)} projection(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
