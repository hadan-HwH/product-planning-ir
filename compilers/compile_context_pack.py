"""Compile a Context Pack per DecisionTarget (plan8 — Phase 4). Generated output.

The AI-facing payload. Built from the CurrentDecisionProjection, it does what a
chunk retriever cannot: it states the current authoritative decision, marks every
inactive option `must_not_use_as_current`, and emits explicit forbidden_inferences
so an agent cannot resurrect a superseded option as the plan.

    Chunking finds related text. A Context Pack fences the current decision.

Usage: python compilers/compile_context_pack.py [--ir <dir>]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ppir.config import REPO_ROOT                                   # noqa: E402
from ppir.atoms import load_atoms, iter_id_refs                     # noqa: E402
from compilers import provenance                                    # noqa: E402
from compilers.compile_decision_projection import project_target, _short  # noqa: E402

BANNER = "<!-- DO NOT EDIT — generated by compile_context_pack from the decision projection. -->"


def _forbidden_inferences(current: list, inactive: list) -> list:
    out = []
    for i in inactive:
        s = _short(i["option"])
        out.append(f"Do not present option {s} as the current decision "
                   f"(status: {i['reason']}).")
        out.append(f"Do not generate requirements or specs for {s} "
                   f"unless explicitly asked about history.")
    if current:
        cur = ", ".join(_short(o) for o in current)
        out.append(f"The current decision is {cur}. If a source says otherwise, "
                   f"treat it as a signal, not the decision.")
    return out


def _open_questions(atoms: dict, target_id: str) -> list:
    out = []
    for e in atoms.values():
        d = e["data"]
        if d.get("kind") == "OpenQuestion" and target_id in set(iter_id_refs(d)):
            out.append({"id": d["id"], "question": d.get("question"),
                        "needed_from": d.get("needed_from")})
    return sorted(out, key=lambda q: q["id"])


def build(atoms: dict, target_id: str) -> dict:
    proj = project_target(atoms, target_id)
    target = atoms.get(target_id, {}).get("data", {})
    current = proj["current_option"]
    inactive = proj["inactive_options"]

    return {
        "kind": "ContextPack",
        "target_ref": target_id,
        "statement": target.get("statement", ""),
        "current_state": proj["current_state"],
        "authority": {
            "current": [{"option": o, "summary": atoms[o]["data"].get("summary")}
                        for o in current if o in atoms],
            "inactive": [{"option": i["option"], "reason": i["reason"],
                          "must_not_use_as_current": True} for i in inactive],
        },
        "history": list(proj["decision_chain"]),
        "forbidden_inferences": _forbidden_inferences(current, inactive),
        "open_questions": _open_questions(atoms, target_id),
        "source_refs": list(proj["source_refs"]),
    }


def render_markdown(pack: dict) -> str:
    L = [BANNER, f"# Context Pack — {pack['target_ref']}", "",
         f"**Decision under question:** {pack['statement']}",
         f"**Current state:** {pack['current_state']}", "",
         "## Authority — the current decision", ""]
    for c in pack["authority"]["current"]:
        L.append(f"- ✅ **{_short(c['option'])}** — {c['summary']}  `{c['option']}`")
    if not pack["authority"]["current"]:
        L.append("- (no active option)")
    L += ["", "### Inactive — MUST NOT use as current", ""]
    for i in pack["authority"]["inactive"]:
        L.append(f"- 🚫 **{_short(i['option'])}** — {i['reason']} "
                 f"(`must_not_use_as_current: true`)  `{i['option']}`")
    L += ["", "## How it got here", ""]
    L += [f"{n}. {step}" for n, step in enumerate(pack["history"], 1)]
    L += ["", "## Forbidden inferences", ""]
    L += [f"- {f}" for f in pack["forbidden_inferences"]]
    if pack["open_questions"]:
        L += ["", "## Open questions", ""]
        L += [f"- {q['question']} (needed from: {q['needed_from']})  `{q['id']}`"
              for q in pack["open_questions"]]
    L += ["", "## Sources", ""]
    L += [f"- `{s}`" for s in pack["source_refs"]]
    return "\n".join(L) + "\n"


def run(ir_dir: Path, out_dir: Path) -> list:
    atoms = load_atoms(ir_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for e in sorted(atoms.values(), key=lambda x: x["data"]["id"]):
        if e["data"].get("kind") != "DecisionTarget":
            continue
        pack = build(atoms, e["data"]["id"])
        md = out_dir / f"{e['data']['id']}.md"
        md.write_text(provenance.stamp(render_markdown(pack), "context_pack", atoms),
                      encoding="utf-8")
        yml = out_dir / f"{e['data']['id']}.yaml"
        yml_body = BANNER + "\n" + yaml.safe_dump(pack, allow_unicode=True, sort_keys=False)
        yml.write_text(provenance.stamp(yml_body, "context_pack", atoms, style="yaml"),
                       encoding="utf-8")
        written += [md, yml]
    return written


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ir", default="ir")
    ap.add_argument("--out", default="compiled/context-packs")
    args = ap.parse_args()
    out = Path(args.out)
    written = run(REPO_ROOT / args.ir, out if out.is_absolute() else REPO_ROOT / out)
    for p in written:
        try:
            print(f"  wrote {p.relative_to(REPO_ROOT)}")
        except ValueError:
            print(f"  wrote {p}")
    print(f"compile_context_pack — {len(written)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
